func CreateOrLoadServerKeys(privateKeyPath string) (ssh.Signer, error) {

	//If we have already created a private key (or there is one in the current directory) dont overwrite/create another one
	if _, err := os.Stat(privateKeyPath); os.IsNotExist(err) {

		privateKeyPem, err := internal.GeneratePrivateKey()
		if err != nil {
			return nil, fmt.Errorf("unable to generate private key, and no private key specified: %s", err)
		}

		err = os.WriteFile(privateKeyPath, privateKeyPem, 0600)
		if err != nil {
			return nil, fmt.Errorf("unable to write private key to disk: %s", err)
		}
	}

	privateBytes, err := os.ReadFile(privateKeyPath)
	if err != nil {
		return nil, fmt.Errorf("failed to load private key (%s): %s", privateKeyPath, err)
	}

	private, err := ssh.ParsePrivateKey(privateBytes)
	if err != nil {
		return nil, fmt.Errorf("failed to parse private key: %s", err)
	}

	return private, nil
}

func Run(config config.Config, autogeneratedConnectBack bool) {
	c := mux.MultiplexerConfig{
		Control:           true,
		Downloads:         config.EnableClientDownloads,
		TLS:               config.TLS,
		TLSCertPath:       config.TLSCert,
		TLSKeyPath:        config.TLSKey,
		AutoTLSCommonName: config.ExternalAddress,
		TcpKeepAlive:      config.Timeout,
		PollingAuthChecker: func(key string, addr net.Addr) bool {

			authorizedKey, err := hex.DecodeString(key)
			if err != nil {
				return false
			}

			pubKey, err := ssh.ParsePublicKey(authorizedKey)
			if err != nil {
				return false
			}

			_, err = CheckAuth(filepath.Join(config.DataDir, "authorized_controllee_keys"), pubKey, getIP(addr.String()), config.Insecure)
			return err == nil

		},
	}

	privateKeyPath := filepath.Join(config.DataDir, "id_ed25519")

	log.Println("Version: ", internal.Version)
	var err error
	multiplexer.ServerMultiplexer, err = mux.ListenWithConfig("tcp", config.ListenAddress, c)
	if err != nil {
		log.Fatalf("Failed to listen on %s (%s)", config.ListenAddress, err)
	}
	defer multiplexer.ServerMultiplexer.Close()

	log.Printf("Listening on %s\n", config.ListenAddress)

	private, err := CreateOrLoadServerKeys(privateKeyPath)
	if err != nil {
		log.Fatal(err)
	}

	log.Printf("Loading private key from: %s\n", privateKeyPath)

	log.Println("Server key fingerprint: ", internal.FingerprintSHA256Hex(private.PublicKey()))

	if config.EnableClientDownloads {
		addr := config.ListenAddress
		if len(config.ExternalAddress) != 0 {
			addr = config.ExternalAddress
		}
		go webserver.Start(multiplexer.ServerMultiplexer.HTTPDownloadRequests(), addr, autogeneratedConnectBack, "../", config.DataDir, private.PublicKey())
		go tcp.Start(multiplexer.ServerMultiplexer.TCPDownloadRequests())
	}

	err = data.LoadDatabase(filepath.Join(config.DataDir, "data.db"))
	if err != nil {
		log.Fatal(err)
	}

	go webhooks.StartWebhooks()

	StartSSHServer(multiplexer.ServerMultiplexer.ControlRequests(), private, config.Insecure, config.OpenProxy, config.DataDir, config.Timeout)
}
