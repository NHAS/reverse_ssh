func TestParseListenAddress(t *testing.T) {
	tests := []struct {
		name    string
		args    []string
		wantErr bool
		want    string
	}{
		{"no address", nil, true, ""},
		{"not host:port", []string{"notanaddress"}, true, ""},
		{"port only", []string{":3232"}, false, ":3232"},
		{"ipv4", []string{"127.0.0.1:3232"}, false, "127.0.0.1:3232"},
		{"ipv6", []string{"[::1]:3232"}, false, "[::1]:3232"},
		{"address is last argument", []string{"--insecure", "0.0.0.0:2222"}, false, "0.0.0.0:2222"},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			clearEnv(t)
			restoreLabel(t)
			args := newArgs(tt.args...)

			cfg, _, err := parse(args)
			if tt.wantErr {
				if err == nil {
					t.Fatalf("expected error, got config %+v", cfg)
				}
				return
			}
			if err != nil {
				t.Fatalf("unexpected error: %v", err)
			}
			if cfg.ListenAddress != tt.want {
				t.Errorf("ListenAddress = %q, want %q", cfg.ListenAddress, tt.want)
			}
		})
	}
}

func TestParseDefaults(t *testing.T) {
	clearEnv(t)
	restoreLabel(t)
	wantLabel := internal.ConsoleLabel
	args := newArgs("127.0.0.1:3232")

	cfg, autogen, err := parse(args)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}

	if cfg.DataDir != "." {
		t.Errorf("DataDir = %q, want %q", cfg.DataDir, ".")
	}
	if cfg.Timeout != 5 {
		t.Errorf("Timeout = %d, want 5", cfg.Timeout)
	}
	if cfg.ConsoleLabel != wantLabel {
		t.Errorf("ConsoleLabel = %q, want %q", cfg.ConsoleLabel, wantLabel)
	}
	if cfg.Insecure || cfg.OpenProxy || cfg.TLS || cfg.EnableClientDownloads {
		t.Errorf("boolean options should default to false: %+v", cfg)
	}
	if !autogen {
		t.Error("expected autogeneratedConnectBack to be true when no external address is given")
	}
	if cfg.ExternalAddress != "127.0.0.1:3232" {
		t.Errorf("ExternalAddress = %q, want listen address", cfg.ExternalAddress)
	}
}

func TestParseExternalAddress(t *testing.T) {
	t.Run("supplied on cli", func(t *testing.T) {
		clearEnv(t)
		restoreLabel(t)
		args := newArgs("--external_address", "example.com:443", "127.0.0.1:3232")

		cfg, autogen, err := parse(args)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if cfg.ExternalAddress != "example.com:443" {
			t.Errorf("ExternalAddress = %q", cfg.ExternalAddress)
		}
		if autogen {
			t.Error("autogeneratedConnectBack should be false when supplied")
		}
	})

	t.Run("wildcard listen picks a concrete host or falls back", func(t *testing.T) {
		clearEnv(t)
		restoreLabel(t)
		args := newArgs(":3232")

		cfg, autogen, err := parse(args)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if !autogen {
			t.Error("expected autogenerated external address")
		}
		// Either an interface address was found, or we fell back to the listen address.
		if !strings.HasSuffix(cfg.ExternalAddress, ":3232") {
			t.Errorf("ExternalAddress = %q, want suffix :3232", cfg.ExternalAddress)
		}
	})
}

