func TestParseDataDir(t *testing.T) {
	t.Run("valid directory is made absolute", func(t *testing.T) {
		clearEnv(t)
		restoreLabel(t)
		dir := t.TempDir()
		args := newArgs("--datadir", dir, "127.0.0.1:3232")

		cfg, _, err := parse(args)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if cfg.DataDir != dir {
			t.Errorf("DataDir = %q, want %q", cfg.DataDir, dir)
		}
		if !filepath.IsAbs(cfg.DataDir) {
			t.Errorf("DataDir %q should be absolute", cfg.DataDir)
		}
	})

	t.Run("nonexistent", func(t *testing.T) {
		clearEnv(t)
		restoreLabel(t)
		missing := filepath.Join(t.TempDir(), "does-not-exist")
		args := newArgs("--datadir", missing, "127.0.0.1:3232")

		if _, _, err := parse(args); err == nil {
			t.Fatal("expected error for missing datadir")
		}
	})

	t.Run("is a file not a directory", func(t *testing.T) {
		clearEnv(t)
		restoreLabel(t)
		file := filepath.Join(t.TempDir(), "file.txt")
		if err := os.WriteFile(file, []byte("x"), 0o600); err != nil {
			t.Fatal(err)
		}
		args := newArgs("--datadir", file, "127.0.0.1:3232")

		_, _, err := parse(args)
		if err == nil || !strings.Contains(err.Error(), "not a directory") {
			t.Fatalf("expected 'not a directory' error, got %v", err)
		}
	})
}

